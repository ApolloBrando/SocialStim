        /// <summary>Rejects missing required entries before setup or a run can mutate state.</summary>
        public static void Validate(TextTemplates text)
        {
            if (text == null) throw new ArgumentNullException(nameof(text));
            var keys = new HashSet<string>(text.Keys, StringComparer.Ordinal);
            foreach (string key in Required)
                if (!keys.Contains(key)) throw new ArgumentException("Missing required text ID: " + key);
        }
