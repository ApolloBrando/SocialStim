        /// <summary>Rejects missing entries or unavailable variables before setup or a run can mutate state.</summary>
        public static void Validate(TextTemplates text)
        {
            if (text == null) throw new ArgumentNullException(nameof(text));
            var keys = new HashSet<string>(text.Keys, StringComparer.Ordinal);
            foreach (var binding in Required)
            {
                if (!keys.Contains(binding.Key)) throw new ArgumentException("Missing required text ID: " + binding.Key);
                if (text.Variables(binding.Key).Any(variable => !binding.Value.Contains(variable)))
                    throw new ArgumentException(binding.Key + ": template requests an unavailable variable.");
            }
        }
